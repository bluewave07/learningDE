#!/usr/bin/env node
/**
 * Generates sw.js: a service worker that precaches every file of the app so it works offline.
 * The cache name contains a hash of all files, so any content change ships a new cache version.
 *   node scripts/build-sw.mjs          write sw.js
 *   node scripts/build-sw.mjs --check  exit 1 if sw.js is out of date (used by validate / CI)
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const list = (dir) => readdirSync(join(root, dir)).filter((f) => !f.startsWith(".")).sort().map((f) => `${dir}/${f}`);
const files = ["index.html", "manifest.webmanifest", ...list("css"), ...list("js"), ...list("data"), ...list("icons")];

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest("hex").slice(0, 10);

const sw = `/* Generated by scripts/build-sw.mjs – do not edit by hand. */
const CACHE = "learningde-${version}";
const FILES = ${JSON.stringify(["./", ...files], null, 2)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("learningde-") && k !== CACHE).map(async (k) => {
        // move already downloaded audio clips into the new cache so they survive app updates
        const old = await caches.open(k), now = await caches.open(CACHE);
        for (const req of await old.keys()) if (req.url.includes("/audio/de/") && req.url.endsWith(".mp3")) { const r = await old.match(req); if (r) await now.put(req, r); }
        return caches.delete(k);
      })))
      .then(() => self.clients.claim())
  );
});

/* cache first – the whole app is precached, so it starts instantly and works offline.
   Audio clips are content-addressed (id = hash of the text) and cached once played.
   The audio index changes when clips are added, so it is fetched network-first. */
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== self.location.origin || e.request.headers.has("range")) return;
  if (url.pathname.endsWith("/audio/de/index.json")) {
    e.respondWith(fetch(e.request).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    }).catch(() => caches.match(e.request, { ignoreSearch: true })));
    return;
  }
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    }).catch(() => (url.pathname.endsWith(".mp3") ? Response.error() : caches.match("./index.html"))))
  );
});
`;

const target = join(root, "sw.js");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== sw) {
    console.error("✖ sw.js is out of date – run: npm run build:sw");
    process.exit(1);
  }
  console.log(`✔ sw.js is up to date (${files.length} files, cache ${version})`);
} else {
  writeFileSync(target, sw);
  console.log(`sw.js written: ${files.length} files, cache learningde-${version}`);
}
